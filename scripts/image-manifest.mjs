// Lists the image stems present in public/img (name-640/960/1440/2200.avif + .webp + name.jpg)
// and the partner badges in public/img/partners
// so pages render the local photo when it exists and fall back otherwise.
import { readdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const dir = resolve(root, "public", "img");
const widths = [640, 960, 1440, 2200];

let files = [];
try {
  files = await readdir(dir);
} catch {
  // No image package installed yet.
}
let partners = [];
try {
  partners = await readdir(resolve(dir, "partners"));
} catch {
  // No partner badges yet; the rail shows brand names as text.
}
// Share images (public/og/<stem>.jpg, built by scripts/og-images.mjs). A page without one uses /brand/og-image.jpg.
let og = [];
try {
  og = (await readdir(resolve(root, "public", "og"))).filter((f) => f.endsWith(".jpg")).map((f) => f.slice(0, -4));
} catch {
  // No share images built yet.
}
const have = new Set(files);
const stems = [...new Set(files.filter((f) => f.endsWith(".jpg")).map((f) => f.slice(0, -4)))]
  .filter((stem) => widths.every((w) => have.has(`${stem}-${w}.avif`) && have.has(`${stem}-${w}.webp`)))
  .sort();

await writeFile(
  resolve(root, "app", "image-manifest.generated.ts"),
  `// Generated by scripts/image-manifest.mjs. Do not edit.\nexport const localImages: ReadonlySet<string> = new Set(${JSON.stringify(stems, null, 2)});\n` +
    `export const localFiles: ReadonlySet<string> = new Set(${JSON.stringify(files.sort(), null, 2)});\n` +
    `export const partnerFiles: ReadonlySet<string> = new Set(${JSON.stringify(partners.sort(), null, 2)});\n` +
    `export const ogImages: ReadonlySet<string> = new Set(${JSON.stringify(og.sort(), null, 2)});\n`,
);
console.log(`image manifest: ${stems.length} local image(s)`);
